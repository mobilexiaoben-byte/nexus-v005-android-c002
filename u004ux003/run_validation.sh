check no_webview_debug bash -c "! grep -Fq 'setWebContentsDebuggingEnabled(true)' '$MAIN'"
check node_syntax node --check "$CHAT"
check no_add_javascript_interface_main bash -c "! grep -Fq 'addJavascriptInterface' '$MAIN'"
check no_add_javascript_interface_bridge bash -c "! grep -Fq 'addJavascriptInterface' '$BRIDGE'"

echo "U004_UX_SHELL_003_STATIC_RESULT pass=$PASS fail=$FAIL"
